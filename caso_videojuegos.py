import pandas as pd
import matplotlib.pyplot as plt
import numpy as np

# 1) Leer el CSV (ajusta la ruta si trabajas en Colab)
df = pd.read_csv('/content/drive/MyDrive/mae_lucho/Proy_inv/videojuegos/vgsales.csv')

# 2) Región que quieres analizar
region = 'EU_Sales'            # o 'NA_Sales', 'JP_Sales', 'Other_Sales'

# 3) Preparar datos (quitar nulos)
sub = df[[region, 'Global_Sales']].dropna()

# 4) Correlación y línea de tendencia (para dar contexto)
corr = sub[region].corr(sub['Global_Sales'])
m, b = np.polyfit(sub[region], sub['Global_Sales'], 1)

# 5) Scatter plot mejorado
plt.figure(figsize=(8, 6))
plt.scatter(sub[region], sub['Global_Sales'], s=30, alpha=0.5)

# Línea de tendencia
x_vals = np.linspace(sub[region].min(), sub[region].max(), 100)
plt.plot(x_vals, m * x_vals + b, linestyle='--', label=f'Tendencia (R = {corr:.2f})')

# Etiquetas y estilo
plt.xlabel(f'Ventas en {region.split("_")[0]} (millones)')
plt.ylabel('Ventas globales (millones)')
plt.title(f'Relación entre ventas en {region.split("_")[0]} y ventas globales')
plt.grid(True, linestyle='--', alpha=0.3)
plt.legend()
