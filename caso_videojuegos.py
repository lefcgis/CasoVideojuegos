import pandas as pd
import matplotlib.pyplot as plt

# 1) Leer CSV (ajusta la ruta si estás en Colab)
df = pd.read_csv('/content/drive/MyDrive/mae_lucho/Proy_inv/videojuegos/vgsales.csv')

# 2) Columnas de ventas regionales
regiones = ['NA_Sales', 'EU_Sales', 'JP_Sales', 'Other_Sales']

# 3) Agregar ventas por plataforma y región
plat_sales = (
    df.groupby('Platform')[regiones + ['Global_Sales']]
      .sum()
      .sort_values('Global_Sales', ascending=False)
)

# 4) Seis plataformas más populares
top_platforms = plat_sales.head(6)

# 5) Gráfico de barras apiladas
fig, ax = plt.subplots(figsize=(10, 6))
top_platforms[regiones].plot(kind='bar', stacked=True, width=0.7, ax=ax)

# 6) Etiquetas de valor en cada segmento y total arriba
for i, plataforma in enumerate(top_platforms.index):
    total = 0
    for reg in regiones:
        value = top_platforms.loc[plataforma, reg]
        # Altura acumulada para colocar texto en el centro de cada segmento
        y_center = total + value / 2
        if value > 0:
            ax.text(i, y_center, f'{value:.0f}',
                    ha='center', va='center', fontsize=8, color='white')
        total += value
    # Etiqueta del total arriba de la barra
    ax.text(i, total + 10, f'{total:.0f}',
            ha='center', va='bottom', fontsize=9, fontweight='bold')

# 7) Estilo
ax.set_xlabel('Plataforma')
ax.set_ylabel('Ventas regionales (millones)')
ax.set_title('Impacto regional en las plataformas más populares')
ax.legend(title='Región')
plt.tight_layout()
plt.show()

