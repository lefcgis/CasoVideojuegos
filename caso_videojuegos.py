def plot_top10_comparison(df, category_col, value_col, top_n=20):
    # 1. Agrupar y calcular la suma del valor de comparación
    grouped = df.groupby(category_col)[value_col].sum().reset_index()
    grouped.columns = [category_col, 'Total']

    # 2. Ordenar y seleccionar Top 10
    top_data = grouped.sort_values('Total', ascending=False).head(top_n)
    others_total = grouped.sort_values('Total', ascending=False)['Total'][top_n:].sum()

    # 3. Agregar fila "Otros"
    if others_total > 0:
        others_row = pd.DataFrame({category_col: ['Otros'], 'Total': [others_total]})
        plot_data = pd.concat([top_data, others_row])
    else:
        plot_data = top_data

    # 4. Crear gráfico
    fig = px.bar(plot_data,
                 x=category_col,
                 y='Total',
                 title=f'Top {top_n} {category_col} por {value_col} vs Otros',
                 color=category_col,
                 text='Total',
                 labels={'Total': f'Total {value_col}'})

    # 5. Personalizar
    fig.update_layout(
        xaxis_title=None,
        xaxis={'categoryorder': 'total descending'},
        hovermode="x unified",
        showlegend=False
    )

    fig.update_traces(
        texttemplate='%{y:,.1f}',
        textposition='outside',
        hovertemplate=f"<b>%{{x}}</b><br>{value_col}: %{{y:,.1f}}"
    )

    fig.show()

# Generar gráficos para cada categoría
for category in colCat:
    plot_top10_comparison(dataVGC, category, valor_comparacion)

